"""ml/datasets.py — data factory loading for SAT (SAT-ML.md §2).

Expects data generated by the C++ simulator's dataset export mode:

    sat-tracker --gen-dataset --sweep ml/sweeps/centroid_v2.toml --out data/centroid_v2/

which writes:

    data/centroid_v2/
    ├── manifest.json
    ├── train/  shard_0000.npz  shard_0001.npz  ...
    ├── val/    shard_0000.npz  ...
    └── test/   shard_0000.npz  ...

Each shard is an .npz with aligned arrays: patches, scalars, labels, run_id,
scenario_id, seed, conditions.

THE SPLITTING RULE (§2.3), and why this file enforces it rather than trusting
the generator: frames within one run are near-duplicates — the beacon moves a
few pixels between them. If frames were shuffled before splitting, near-
identical images would land in both train and test, inflating the test score
and hiding exactly the generalisation gap the evaluators' unseen MP4 files
will expose. So the split key is (scenario_id, seed), never frame index, and
`verify_split_disjoint` below is a hard assertion you should call once after
every dataset generation — not just documentation.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator

import numpy as np
from torch.utils.data import Dataset


# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Manifest:
    """§2.4 — what a dataset directory claims about itself."""

    task: str                    # "centroid_patches" | "candidates" | "tracks" | "strategy"
    patch_px: int
    n_samples: dict[str, int]    # {"train": N, "val": N, "test": N}
    scenarios: dict[str, list[str]]  # which scenario names appear in each split
    seed_ranges: dict[str, tuple[int, int]]
    sha256: str

    @classmethod
    def load(cls, root: Path) -> "Manifest":
        with open(root / "manifest.json") as f:
            d = json.load(f)
        return cls(
            task=d["task"],
            patch_px=d["patch_px"],
            n_samples=d["n_samples"],
            scenarios=d["scenarios"],
            seed_ranges={k: tuple(v) for k, v in d["seed_ranges"].items()},
            sha256=d["sha256"],
        )


def verify_split_disjoint(root: Path) -> None:
    """Hard assertion for ML-3 / §2.3: no (scenario_id, seed) pair may appear
    in more than one split. Raises AssertionError naming the offending pairs
    rather than silently passing a leaky split into training.

    Call this once, right after `--gen-dataset` finishes, before anything
    else touches the data. It is cheap (reads only the small id arrays, not
    the patches) and it is the single most important check in this file.
    """
    root = Path(root)
    keys_by_split: dict[str, set[tuple[int, int]]] = {}
    for split in ("train", "val", "test"):
        keys: set[tuple[int, int]] = set()
        for shard_path in sorted((root / split).glob("shard_*.npz")):
            with np.load(shard_path) as z:
                for scen, seed in zip(z["scenario_id"], z["seed"]):
                    keys.add((int(scen), int(seed)))
        keys_by_split[split] = keys

    train, val, test = keys_by_split["train"], keys_by_split["val"], keys_by_split["test"]
    overlaps = {
        "train/val": train & val,
        "train/test": train & test,
        "val/test": val & test,
    }
    leaky = {pair: overlap for pair, overlap in overlaps.items() if overlap}
    if leaky:
        detail = "; ".join(f"{pair}: {len(ov)} shared (scenario_id, seed) keys" for pair, ov in leaky.items())
        raise AssertionError(
            f"Dataset split is leaky — {detail}. "
            "Regenerate with a run-level split (§2.3); do not train on this data."
        )


# ---------------------------------------------------------------------------
# Normalisation (§2.5)
# ---------------------------------------------------------------------------

def normalise_patch(patch: np.ndarray) -> np.ndarray:
    """Per-patch normalisation: background-subtract then scale to unit range.

    Applied identically at train and inference time — the ONNX parity test
    (ml/tests/test_parity.py) exercises this path, so any drift here shows up
    as a parity failure rather than a silent accuracy regression.
    """
    floor = np.percentile(patch, 10)  # robust background estimate, ignores the beacon itself
    p = patch.astype(np.float32) - floor
    peak = p.max()
    if peak > 1e-6:
        p = p / peak
    return np.clip(p, 0.0, 1.0)


def normalise_scalars(scalars: np.ndarray, snr_range=(0.0, 40.0), size_range=(0.0, 30.0)) -> np.ndarray:
    """scalars = [snr, size_est] → both mapped to roughly [0, 1]."""
    out = scalars.astype(np.float32).copy()
    out[..., 0] = np.clip((out[..., 0] - snr_range[0]) / (snr_range[1] - snr_range[0]), 0.0, 1.0)
    out[..., 1] = np.clip((out[..., 1] - size_range[0]) / (size_range[1] - size_range[0]), 0.0, 1.0)
    return out


def normalise_candidate_scalars(scalars: np.ndarray) -> np.ndarray:
    """Normalise CandidateNet's six tracker features without changing priors.

    CandidateNet receives proposal measurements, not truth-derived values:
    ``[snr, area, fill_ratio, aspect, matched_response,
    dist_from_prediction]``.  The ranges are physical feature ranges from
    SAT-ML.md section 5.2; clipping only bounds numerical outliers and does
    not resample or augment the data.
    """
    out = scalars.astype(np.float32).copy()
    ranges = ((0.0, 40.0), (0.0, 400.0), (0.0, 1.0), (1.0, 3.0), (0.0, 100.0), (0.0, 500.0))
    if out.shape[-1] != len(ranges):
        raise ValueError(f"expected six candidate scalars, got shape {out.shape}")
    for index, (lo, hi) in enumerate(ranges):
        out[..., index] = np.clip((out[..., index] - lo) / (hi - lo), 0.0, 1.0)
    return out


# ---------------------------------------------------------------------------
# Dataset
# ---------------------------------------------------------------------------

class CentroidPatchDataset(Dataset):
    """Loads every shard in one split into memory. Shards are small (a few
    thousand 15x15 patches each per §2.2's max_per_run), so for the sizes
    this project generates, eager loading is simpler and fast enough; switch
    to a lazy/mmap loader only if a specific split stops fitting in RAM.
    """

    def __init__(self, root: Path, split: str, patch_px: int = 15):
        self.root = Path(root)
        self.split = split
        self.patch_px = patch_px

        patches, scalars, labels, run_id, scenario_id, seed = [], [], [], [], [], []
        shard_paths = sorted((self.root / split).glob("shard_*.npz"))
        if not shard_paths:
            raise FileNotFoundError(
                f"No shards found under {self.root / split}. "
                "Generate data first with `sat-tracker --gen-dataset ...` "
                "(SAT-ML.md §2.2) before constructing this dataset."
            )
        for shard_path in shard_paths:
            with np.load(shard_path) as z:
                patches.append(z["patches"])
                scalars.append(z["scalars"])
                labels.append(z["labels"])
                run_id.append(z["run_id"])
                scenario_id.append(z["scenario_id"])
                seed.append(z["seed"])

        self.patches = np.concatenate(patches, axis=0)
        self.scalars = np.concatenate(scalars, axis=0)
        self.labels = np.concatenate(labels, axis=0)
        self.run_id = np.concatenate(run_id, axis=0)
        self.scenario_id = np.concatenate(scenario_id, axis=0)
        self.seed = np.concatenate(seed, axis=0)

        assert self.patches.shape[1:] == (patch_px, patch_px), (
            f"Expected {patch_px}x{patch_px} patches, got {self.patches.shape[1:]} — "
            "check the sweep config's [capture] patch_px matches this dataset's constructor arg."
        )

    def __len__(self) -> int:
        return len(self.patches)

    def __getitem__(self, idx: int):
        patch = normalise_patch(self.patches[idx])[None, ...]         # (1, P, P)
        scalars = normalise_scalars(self.scalars[idx])                # (2,)
        target = self.labels[idx].astype(np.float32)                  # (dx, dy) in pixels
        return patch, scalars, target


class CandidatePatchDataset(Dataset):
    """Load candidate shards using the same run-disjoint data contract."""

    def __init__(self, root: Path, split: str, patch_px: int = 15):
        self.root = Path(root)
        self.split = split
        shard_paths = sorted((self.root / split).glob("shard_*.npz"))
        if not shard_paths:
            raise FileNotFoundError(f"No shards found under {self.root / split}")
        arrays = {key: [] for key in ("patches", "scalars", "labels", "run_id", "scenario_id", "seed")}
        for shard_path in shard_paths:
            with np.load(shard_path) as z:
                for key in arrays:
                    arrays[key].append(z[key])
        self.patches = np.concatenate(arrays["patches"], axis=0)
        self.scalars = np.concatenate(arrays["scalars"], axis=0)
        self.labels = np.concatenate(arrays["labels"], axis=0).astype(np.int64)
        self.run_id = np.concatenate(arrays["run_id"], axis=0)
        self.scenario_id = np.concatenate(arrays["scenario_id"], axis=0)
        self.seed = np.concatenate(arrays["seed"], axis=0)
        assert self.patches.shape[1:] == (patch_px, patch_px)
        if self.scalars.shape[1] != 6:
            raise ValueError(f"CandidateNet requires six scalars, got {self.scalars.shape[1]}")

    def __len__(self) -> int:
        return len(self.patches)

    def __getitem__(self, idx: int):
        return (
            normalise_patch(self.patches[idx])[None, ...],
            normalise_candidate_scalars(self.scalars[idx]),
            self.labels[idx],
        )
